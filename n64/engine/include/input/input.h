#pragma once
#include <libdragon.h>

/**
 * Input map: named actions (e.g. "jump", "move") bound to controller buttons
 * and sticks in the project settings (Project > Settings > Input).
 *
 * The editor generates "p64/inputMap.h" with one constant per action, so scripts
 * read input by name instead of by button:
 *
 *   #include "p64/inputMap.h"
 *   if(Input::pressed(Action::jump)) { ... }
 *   auto move = Input::stick(Action::move); // x/y in -1..1, mag in 0..1
 *
 * Raw controller access through libdragon (joypad_get_inputs etc.) keeps working
 * alongside this, nothing here takes it over.
 */
namespace P64::Input
{
  /** Bits of ActionDef::binds, one per digital source. */
  enum Bind : uint32_t
  {
    BIND_A       = 1u << 0,
    BIND_B       = 1u << 1,
    BIND_Z       = 1u << 2,
    BIND_START   = 1u << 3,
    BIND_L       = 1u << 4,
    BIND_R       = 1u << 5,
    BIND_D_UP    = 1u << 6,
    BIND_D_DOWN  = 1u << 7,
    BIND_D_LEFT  = 1u << 8,
    BIND_D_RIGHT = 1u << 9,
    BIND_C_UP    = 1u << 10,
    BIND_C_DOWN  = 1u << 11,
    BIND_C_LEFT  = 1u << 12,
    BIND_C_RIGHT = 1u << 13,
    // The analog stick pushed past ActionDef::threshold in one direction
    BIND_STICK_UP    = 1u << 14,
    BIND_STICK_DOWN  = 1u << 15,
    BIND_STICK_LEFT  = 1u << 16,
    BIND_STICK_RIGHT = 1u << 17,
  };

  enum class ActionType : uint8_t
  {
    /** On or off: held while any bound source is held. */
    BUTTON = 0,
    /**
     * A 2D direction. binds selects the sources: any BIND_STICK_* bit uses the
     * analog stick, the D-pad and C-button bits act as digital directions.
     */
    STICK = 1,
  };

  /** One action, as generated by the editor into src/p64/inputMap.cpp. */
  struct ActionDef
  {
    uint32_t binds;
    ActionType type;
    uint8_t threshold; // BUTTON: raw stick units a BIND_STICK_* direction needs
    uint8_t deadzone;  // STICK: raw stick distance from centre that still reads as 0
    uint8_t range;     // STICK: raw stick distance that reads as full (1.0)
    float curve;       // STICK: exponent on the 0..1 magnitude, 1 = linear
  };

  /** Most actions a project can define (the held state is one bitmask). */
  constexpr uint32_t MAX_ACTIONS = 32;

  /** Result of stick(): direction and strength, after deadzones and curve. */
  struct StickValue
  {
    float x{0.0f};   // -1 (left) to 1 (right)
    float y{0.0f};   // -1 (down) to 1 (up)
    float mag{0.0f}; // 0 (centred) to 1 (pushed to the edge)
  };

  /** Called by the engine once per frame, after joypad_poll(). */
  void update(float deltaTime);

  /** True while the action is held. */
  bool held(uint8_t action, joypad_port_t port = JOYPAD_PORT_1);

  /** True only on the frame the action started being held. */
  bool pressed(uint8_t action, joypad_port_t port = JOYPAD_PORT_1);

  /** True only on the frame the action stopped being held. */
  bool released(uint8_t action, joypad_port_t port = JOYPAD_PORT_1);

  /**
   * Like pressed(), but while held it fires again after `delay` seconds and
   * then every `rate` seconds. Meant for menu cursors.
   */
  bool repeated(uint8_t action, joypad_port_t port = JOYPAD_PORT_1, float delay = 0.4f, float rate = 0.1f);

  /** Seconds the action has been held, 0 if it is not held. */
  float heldTime(uint8_t action, joypad_port_t port = JOYPAD_PORT_1);

  /**
   * Direction and strength of a STICK action. For a BUTTON action, mag is 1
   * while held and x/y stay 0.
   */
  StickValue stick(uint8_t action, joypad_port_t port = JOYPAD_PORT_1);

  /** Number of actions defined in the project. */
  uint32_t getActionCount();

  /** Name of an action as written in the editor, or "" if out of range. */
  const char* getActionName(uint8_t action);
}
